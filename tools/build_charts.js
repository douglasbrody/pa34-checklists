// Builds charts.js (the traced POH Section 8 charts) from tools/charts/*.json:  node tools/build_charts.js
// Each chart gets a factor so that it reproduces the POH's own printed example exactly, or errs to the safe side
// (distances never shorter, climb rates never higher than the book's example). perf.js is the reading engine.
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const PC = new Function(fs.readFileSync(path.join(root, 'perf.js'), 'utf8') + '; return PERFCHART;')();
const IDS = ['8-2', '8-3', '8-4', '8-5', '8-6', '8-7', '8-8', '8-13', '8-14'];
const out = {};
for (const id of IDS) {
  const c = JSON.parse(fs.readFileSync(path.join(__dirname, 'charts', id + '.json'), 'utf8'));
  delete c.factor; delete c.factorNote;
  c.img = 'charts/' + id + '.jpg';
  c.yTitle = { '8-2': 'TAKEOFF GROUND RUN — FT', '8-3': 'TAKEOFF GROUND RUN — FT', '8-4': 'TAKEOFF DISTANCE OVER 50 FT — FT', '8-5': 'TAKEOFF DISTANCE OVER 50 FT — FT',
    '8-6': 'ACCELERATE-STOP DISTANCE — FT', '8-13': 'LANDING GROUND RUN — FT', '8-14': 'LANDING DISTANCE OVER 50 FT — FT' }[id];
  const ex = c.example, r = PC.read(JSON.parse(JSON.stringify(c)), ex), raw = r.raw;
  if (raw === null) throw new Error(id + ': the printed example does not read');
  const climb = c.kind === 'climb', f = ex.answer / raw;
  const rounded = climb ? Math.floor(raw / 10 + 1e-9) * 10 : Math.ceil(raw / 10 - 1e-9) * 10;   // as the app shows it
  if (climb ? rounded > ex.answer : rounded < ex.answer) {   // a factor only where rounding alone does not give the POH example
    c.factor = f;
    if (Math.abs(f - 1) >= 0.01) c.factorNote = 'Readings ×' + f.toFixed(3) + ' so this chart gives the POH example (' + ex.answer + (climb ? ' fpm' : ' ft') + '; the traced lines give ' + Math.round(raw) + ')';
  }
  const chk = PC.read(JSON.parse(JSON.stringify(c)), ex);
  const err = (chk.raw - ex.answer) / ex.answer * 100;
  console.log(id.padEnd(5), 'example', ex.answer, 'traced', raw.toFixed(1), 'factor', (c.factor || 1).toFixed(4), '->', chk.value, '(' + (err >= 0 ? '+' : '') + err.toFixed(2) + '%)', chk.speed ? 'speed ' + chk.speed + ' (POH ' + ex.speed + ')' : '');
  out[id] = c;
}
const js = '// Generated by tools/build_charts.js from tools/charts/*.json (traced POH Section 8 charts). Do not edit.\nvar POH_CHARTS = ' + JSON.stringify(out) + ';\n';
fs.writeFileSync(path.join(root, 'charts.js'), js);
console.log('charts.js', (js.length / 1024).toFixed(0), 'KB');
